#!/usr/bin/env python3
"""Generate PROJECT_STRUCTURE.md and enforce the 100-direct-file directory limit."""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "PROJECT_STRUCTURE.md"
DIRECT_FILE_LIMIT = 100
IGNORED_DIRS = {
    ".git", "__pycache__", ".pytest_cache", ".mypy_cache", ".ruff_cache",
    ".venv", "venv", "env", ".cache", "runtime", "logs", "backups",
    "node_modules", "dist", "build",
}
IGNORED_SUFFIXES = {".pyc", ".pyo", ".log", ".dump", ".pem", ".key", ".sqlite", ".sqlite3"}
IGNORED_NAMES = {".DS_Store", "Thumbs.db", "sonar_config.json", "secret.key"}


def visible_entries(directory: Path):
    directories = []
    files = []
    try:
        entries = list(os.scandir(directory))
    except OSError as exc:
        raise RuntimeError(f"Cannot read {directory}: {exc}") from exc

    for entry in entries:
        name = entry.name
        if entry.is_symlink():
            # Do not traverse symlinks in a generated repository map.
            continue
        if entry.is_dir(follow_symlinks=False):
            if name not in IGNORED_DIRS:
                directories.append(name)
        elif entry.is_file(follow_symlinks=False):
            path = Path(name)
            if name in IGNORED_NAMES or path.suffix.lower() in IGNORED_SUFFIXES:
                continue
            if name == ".env" or (name.startswith(".env.") and name != ".env.example"):
                continue
            files.append(name)

    return sorted(directories, key=str.casefold), sorted(files, key=str.casefold)


def walk(directory: Path, relative: str = "."):
    directories, files = visible_entries(directory)
    direct_count = len(files)
    yield relative, direct_count
    for name in directories:
        child = directory / name
        child_rel = name if relative == "." else f"{relative}/{name}"
        yield from walk(child, child_rel)


def render_tree(directory: Path, prefix: str = ""):
    directories, files = visible_entries(directory)
    entries = [(name, True) for name in directories] + [(name, False) for name in files]
    entries.sort(key=lambda item: (not item[1], item[0].casefold()))
    lines = []
    for index, (name, is_dir) in enumerate(entries):
        last = index == len(entries) - 1
        branch = "└── " if last else "├── "
        lines.append(prefix + branch + name + ("/" if is_dir else ""))
        if is_dir:
            child_prefix = prefix + ("    " if last else "│   ")
            lines.extend(render_tree(directory / name, child_prefix))
    return lines


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check-limits",
        action="store_true",
        help="check the 100-direct-file limit without rewriting the structure file",
    )
    args = parser.parse_args()

    # Ensure the output file appears in its own generated tree on first run.
    OUTPUT.touch(exist_ok=True)
    counts = list(walk(ROOT))
    violations = [(path, count) for path, count in counts if count > DIRECT_FILE_LIMIT]
    if violations:
        for path, count in violations:
            print(f"LIMIT EXCEEDED: {path} has {count} direct files (max {DIRECT_FILE_LIMIT})", file=sys.stderr)
        return 1

    if args.check_limits:
        print(f"Directory file-count check passed: {len(counts)} directories, limit {DIRECT_FILE_LIMIT}.")
        return 0

    total_files = sum(count for _, count in counts)
    tree = "\n".join(render_tree(ROOT))
    content = (
        "# Project Structure\n\n"
        "> Generated by `python3 scripts/update_project_structure.py`. "
        "Do not edit this file manually.\n"
        f"> Visible files: **{total_files}** · Direct files per directory: **≤ {DIRECT_FILE_LIMIT}**.\n\n"
        "```text\n.\n"
        f"{tree}\n"
        "```\n"
    )
    OUTPUT.write_text(content, encoding="utf-8")
    print(f"Updated {OUTPUT.relative_to(ROOT)} ({total_files} visible files; {len(counts)} directories checked).")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
